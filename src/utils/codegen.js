// ─────────────────────────────────────────────────────────────
// codegen.js — turns the layout tree into React JSX + CSS, a
// runnable Vite project, or a portable design file. Pure
// functions only, so the output is easy to test.
// ─────────────────────────────────────────────────────────────
import { ICON_MARKUP } from "../constants/icons";
import { KEYFRAMES, keyframesCSS } from "../constants/motion";
import { NON_CSS_KEYS, buildTransform } from "./styleKeys";

const kebab = (s) => s.replace(/([A-Z])/g, "-$1").toLowerCase();
const indent = (n) => "  ".repeat(n);

const TAG_MAP = {
  h1: "h1", h2: "h2", h3: "h3", text: "p", label: "label", button: "button",
  link: "a", nav: "nav", section: "section", blockquote: "blockquote",
  flex: "div", grid: "div", card: "div", "form-group": "div", spacer: "div",
  container: "div", input: "input", textarea: "textarea", select: "select",
  ul: "ul", ol: "ol", code: "pre", table: "table", image: "img",
  video: "video", audio: "audio", iframe: "iframe", divider: "hr", icon: "span",
  checkbox: "label", toggle: "label",
};

/* ── helpers ─────────────────────────────────────────────── */
const SAFE_ATTR = /^[^"{}<>&\n\\]*$/;
const attr = (name, value) =>
  value === undefined || value === null || value === ""
    ? ""
    : SAFE_ATTR.test(String(value))
      ? ` ${name}="${value}"`
      : ` ${name}={${JSON.stringify(String(value))}}`;
const jsxText = (str) =>
  /[{}<>&]/.test(str) ? `{${JSON.stringify(str)}}` : str;
const lines = (content) =>
  String(content || "").split("\n").map((l) => l.trim()).filter(Boolean);

/** Assigns readable, unique class names: rc-artboard, rc-button-1 … */
const buildClassMap = (tree) => {
  const map = new Map();
  const counts = {};
  const walk = (node) => {
    if (node.id === "root") map.set(node.id, "rc-artboard");
    else {
      counts[node.type] = (counts[node.type] || 0) + 1;
      map.set(node.id, `rc-${node.type}-${counts[node.type]}`);
    }
    (node.children || []).forEach(walk);
  };
  walk(tree);
  return map;
};

/* ── CSS ─────────────────────────────────────────────────── */
const buildRule = (selector, styles = {}) => {
  const decl = [];
  for (const [key, val] of Object.entries(styles)) {
    if (val === "" || val == null || val === false) continue;
    if (NON_CSS_KEYS.has(key)) continue;
    decl.push(`  ${kebab(key)}: ${val};`);
  }
  const transform = buildTransform(styles);
  if (transform) decl.push(`  transform: ${transform};`);
  return decl.length ? `${selector} {\n${decl.join("\n")}\n}` : "";
};

const collectUsedAnimations = (node, used = new Set()) => {
  const name = node.styles?.animationName || node.styles?.animationPreset;
  if (name && KEYFRAMES[name]) used.add(name);
  const short = String(node.styles?.animation || "").split(" ")[0];
  if (KEYFRAMES[short]) used.add(short);
  (node.children || []).forEach((c) => collectUsedAnimations(c, used));
  return used;
};

export const generateCSS = (tree, appName = "ReactCanvas") => {
  const classes = buildClassMap(tree);
  const rules = [];
  const walk = (node) => {
    const rule = buildRule(`.${classes.get(node.id)}`, node.styles);
    if (rule) rules.push(rule);
    (node.children || []).forEach(walk);
  };
  walk(tree);
  const used = [...collectUsedAnimations(tree)];
  const header = `/* Generated by ${appName} */\n* { box-sizing: border-box; margin: 0; padding: 0; }\n\n`;
  const kf = used.length ? `\n\n${keyframesCSS(used)}` : "";
  const reduced = used.length
    ? "\n\n@media (prefers-reduced-motion: reduce) {\n  * { animation: none !important; transition: none !important; }\n}"
    : "";
  return header + rules.join("\n\n") + kf + reduced + "\n";
};

/* ── JSX ─────────────────────────────────────────────────── */
const nodeToJSX = (node, depth, classes) => {
  const pad = indent(depth);
  const cls = classes.get(node.id);
  const s = node.styles || {};
  const tag = TAG_MAP[node.type] || "div";
  const c = `className="${cls}"`;

  switch (node.type) {
    case "input":
      return `${pad}<input ${c} type="${node.inputType || "text"}"${attr("placeholder", node.content)} />`;
    case "image":
      return `${pad}<img ${c}${attr("src", s.src)} alt="${s.alt || ""}" />`;
    case "divider":
      return `${pad}<hr ${c} />`;
    case "textarea":
      return `${pad}<textarea ${c}${attr("placeholder", node.content)}${attr("rows", s.rows)}></textarea>`;
    case "select": {
      const opts = lines(node.content)
        .map((o) => `${pad}  <option>${jsxText(o)}</option>`)
        .join("\n");
      return `${pad}<select ${c}>\n${opts}\n${pad}</select>`;
    }
    case "ul":
    case "ol": {
      const items = lines(node.content)
        .map((o) => `${pad}  <li>${jsxText(o)}</li>`)
        .join("\n");
      return `${pad}<${tag} ${c}>\n${items}\n${pad}</${tag}>`;
    }
    case "code":
      return `${pad}<pre ${c}>\n${pad}  <code>{${JSON.stringify(node.content || "")}}</code>\n${pad}</pre>`;
    case "video": {
      const a = [
        attr("src", s.src),
        attr("poster", s.poster),
        s.controls !== "Hide" ? " controls" : "",
        s.autoplay === "On" ? " autoPlay" : "",
        s.loop === "On" ? " loop" : "",
        s.muted === "On" ? " muted" : "",
      ].join("");
      return `${pad}<video ${c}${a} />`;
    }
    case "audio": {
      const a = [
        attr("src", s.src),
        s.controls !== "Hide" ? " controls" : "",
        s.autoplay === "On" ? " autoPlay" : "",
        s.loop === "On" ? " loop" : "",
      ].join("");
      return `${pad}<audio ${c}${a} />`;
    }
    case "iframe": {
      const sandbox = s.sandbox && s.sandbox !== "none" ? attr("sandbox", s.sandbox) : "";
      return `${pad}<iframe ${c}${attr("src", s.src)} title="${s.title || "Embedded content"}"${sandbox} />`;
    }
    case "table": {
      const headers = String(node.tableHeaders || "Col 1,Col 2,Col 3")
        .split(",")
        .map((h) => h.trim());
      const rows = parseInt(node.tableRows) || 3;
      const data = node.tableData || [];
      const head = headers.map((h) => `${pad}      <th>${jsxText(h)}</th>`).join("\n");
      const body = Array.from({ length: rows })
        .map((_, ri) => {
          const cells = headers
            .map((_, ci) => `${pad}      <td>${jsxText(data[ri]?.[ci] || "")}</td>`)
            .join("\n");
          return `${pad}    <tr>\n${cells}\n${pad}    </tr>`;
        })
        .join("\n");
      return `${pad}<table ${c}>\n${pad}  <thead>\n${pad}    <tr>\n${head}\n${pad}    </tr>\n${pad}  </thead>\n${pad}  <tbody>\n${body}\n${pad}  </tbody>\n${pad}</table>`;
    }
    case "icon": {
      const size = parseInt(s.width) || 40;
      const name = node.content || "Star";
      const inner = ICON_MARKUP[name] || ICON_MARKUP.Star;
      const stroke = s.strokeWidth || 1.8;
      return `${pad}<span ${c} role="img" aria-label="${name}">\n${pad}  <svg width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="${stroke}" strokeLinecap="round" strokeLinejoin="round">${inner}</svg>\n${pad}</span>`;
    }
    case "link":
      return `${pad}<a ${c} href="${s.href || "#"}">${jsxText(node.content || "Link")}</a>`;
    case "checkbox":
    case "toggle": {
      const role = node.type === "toggle" ? ' role="switch"' : "";
      const checked = s.checked === "Checked" ? " defaultChecked" : "";
      return `${pad}<label ${c}>\n${pad}  <input type="checkbox"${role}${checked} />\n${pad}  <span>${jsxText(node.content || "")}</span>\n${pad}</label>`;
    }
    case "label": {
      return `${pad}<label ${c}${attr("htmlFor", s.htmlFor)}>${jsxText(node.content || "")}</label>`;
    }
    case "blockquote": {
      const cite = attr("cite", s.cite);
      return `${pad}<blockquote ${c}${cite}>${jsxText(node.content || "")}</blockquote>`;
    }
    default:
  }

  const children = (node.children || []).map((ch) => nodeToJSX(ch, depth + 1, classes));
  const inner = [node.content ? `${pad}  {${JSON.stringify(node.content)}}` : "", ...children].filter(Boolean);
  if (!inner.length) return `${pad}<${tag} ${c}></${tag}>`;
  return `${pad}<${tag} ${c}>\n${inner.join("\n")}\n${pad}</${tag}>`;
};

export const generateJSX = (tree) => {
  const classes = buildClassMap(tree);
  const body = nodeToJSX(tree, 2, classes);
  return `import './App.css';\n\nexport default function App() {\n  return (\n${body}\n  );\n}\n`;
};

/* ── Runnable Vite project ───────────────────────────────── */
const slug = (s) =>
  String(s || "reactcanvas-app")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "") || "reactcanvas-app";

export const generateProjectFiles = (tree, projectName = "ReactCanvas Project") => {
  const name = slug(projectName);
  return {
    [`${name}/package.json`]: JSON.stringify(
      {
        name,
        private: true,
        version: "0.0.0",
        type: "module",
        scripts: { dev: "vite", build: "vite build", preview: "vite preview" },
        dependencies: { react: "^19.0.0", "react-dom": "^19.0.0" },
        devDependencies: { "@vitejs/plugin-react": "^5.0.0", vite: "^7.0.0" },
      },
      null,
      2,
    ) + "\n",
    [`${name}/index.html`]: `<!doctype html>\n<html lang="en">\n  <head>\n    <meta charset="UTF-8" />\n    <meta name="viewport" content="width=device-width, initial-scale=1.0" />\n    <title>${projectName.replace(/[<>&]/g, "")}</title>\n  </head>\n  <body>\n    <div id="root"></div>\n    <script type="module" src="/src/main.jsx"></script>\n  </body>\n</html>\n`,
    [`${name}/vite.config.js`]: `import { defineConfig } from 'vite';\nimport react from '@vitejs/plugin-react';\n\nexport default defineConfig({ plugins: [react()] });\n`,
    [`${name}/src/main.jsx`]: `import { StrictMode } from 'react';\nimport { createRoot } from 'react-dom/client';\nimport App from './App.jsx';\n\ncreateRoot(document.getElementById('root')).render(\n  <StrictMode>\n    <App />\n  </StrictMode>,\n);\n`,
    [`${name}/src/App.jsx`]: generateJSX(tree),
    [`${name}/src/App.css`]: generateCSS(tree, "ReactCanvas"),
    [`${name}/.gitignore`]: "node_modules\ndist\n.env\n.env.*\n!.env.example\n*.log\n.DS_Store\n",
    [`${name}/README.md`]: `# ${projectName}\n\nExported from ReactCanvas.\n\n- \`src/App.jsx\` holds the component tree.\n- \`src/App.css\` holds one class per element.\n`,
  };
};

/* ── Portable design file ────────────────────────────────── */
export const DESIGN_FORMAT = "reactcanvas.design";

export const serializeDesign = ({ tree, name, canvasBg, canvasDotColor }) =>
  JSON.stringify(
    { format: DESIGN_FORMAT, version: 1, name, canvasBg, canvasDotColor, tree },
    null,
    2,
  );

/** Validates a parsed design; returns the tree or throws a readable Error. */
export const parseDesign = (text) => {
  let data;
  try {
    data = JSON.parse(text);
  } catch {
    throw new Error("That file isn’t valid JSON.");
  }
  const tree = data?.format === DESIGN_FORMAT ? data.tree : data;
  if (!isValidTree(tree)) {
    throw new Error("That file isn’t a ReactCanvas design.");
  }
  return { tree, name: data?.name, canvasBg: data?.canvasBg, canvasDotColor: data?.canvasDotColor };
};

export const isValidTree = (node, depth = 0) => {
  if (!node || typeof node !== "object" || depth > 60) return false;
  if (typeof node.id !== "string" || typeof node.type !== "string") return false;
  if (depth === 0 && (node.id !== "root" || node.type !== "container")) return false;
  if (node.children !== undefined && !Array.isArray(node.children)) return false;
  return (node.children || []).every((c) => isValidTree(c, depth + 1));
};
